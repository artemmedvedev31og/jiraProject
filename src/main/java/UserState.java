/**
 * @brief Перечисление состояний диалога пользователя с Telegram-ботом.
 *
 * Текущее состояние определяет, какой обработчик должен принять следующее сообщение.
 */
public enum UserState {
    /** Бот ожидает имя исполнителя для поиска. */
    WAITING_FOR_ARTISTS,
    /** Бот ожидает команду или выбор пункта главного меню. */
    WAITING_FOR_ACTIONS,
    /** Бот ожидает выбор одного из найденных треков. */
    WAITING_FOR_TRACK_SELECTION,
    /** Бот ожидает действие с выбранным треком. */
    WAITING_FOR_TRACK_ACTIONS,
    /** Бот должен отправить текст песни. */
    WAITING_FOR_TEXT,
    /** Бот должен отправить ссылку на музыкальный сервис. */
    WAITING_FOR_LINK
}
